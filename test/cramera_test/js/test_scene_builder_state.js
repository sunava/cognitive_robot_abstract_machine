'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = {window: {}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../../../cramera/src/cramera/web/core/scene-builder-state.js'), 'utf8'), context);
const {SceneBuilderState: State, SceneDocumentError} = context.window;
const plain = (value) => JSON.parse(JSON.stringify(value));
const assets = [{id: 'bench', name: 'Workbench', category: 'Furniture', kind: 'urdf'}, {id: 'pr2', name: 'PR2', category: 'Robots', kind: 'urdf'}];
const state = new State(assets);
assert.equal(state.document.version, State.VERSION);
assert.equal(state.document.instances.length, 0);
const bench = state.add('bench');
const robot = state.add('pr2');
state.transform(robot.id, {position: [2, 1, 0], rotation: [0, 0, Math.PI / 2]});
assert.deepEqual(plain(state.instance(robot.id).position), [2, 1, 0]);
state.transform(bench.id, {position: [0.5, 0, 0], rotation: [0, 0, 0]}, 'cabinet');
assert.deepEqual(plain(state.instance(bench.id).linkOffsets.cabinet.position), [0.5, 0, 0]);
assert.deepEqual(plain(state.instance(bench.id).position), [0, 0, 0]);
state.setJoint(bench.id, 'drawer_joint', 0.3);
const duplicate = state.duplicate(bench.id);
assert.notEqual(duplicate.id, bench.id);
state.setJoint(duplicate.id, 'drawer_joint', 0.1);
assert.equal(state.instance(bench.id).jointPositions.drawer_joint, 0.3);
const exported = state.export();
const restored = new State(assets, JSON.parse(exported));
assert.deepEqual(plain(restored.document), plain(state.document));
state.remove(duplicate.id);
assert.equal(state.instance(duplicate.id), null);
assert.equal(state.undo(), true);
assert.equal(state.instance(duplicate.id).jointPositions.drawer_joint, 0.1);
assert.equal(state.redo(), true);
assert.equal(state.instance(duplicate.id), null);
state.undo();
state.rename('A different scene');
assert.equal(state.redo(), false);
const before = state.export();
assert.throws(() => state.transform(robot.id, {position: [NaN, 0, 0], rotation: [0, 0, 0]}), SceneDocumentError);
assert.equal(state.export(), before);
assert.throws(() => State.validate({...plain(state.document), version: 99}), SceneDocumentError);
assert.throws(() => State.validate({...plain(state.document), instances: [plain(bench), plain(bench)]}), SceneDocumentError);
assert.throws(() => State.validate({...plain(state.document), arbitraryCode: 'no'}), SceneDocumentError);
assert.throws(() => State.validate({...plain(state.document), instances: [{...plain(bench), position: [true, 0, 0]}]}), SceneDocumentError);
assert.throws(() => State.validate({...plain(state.document), instances: [{...plain(bench), linkOffsets: JSON.parse('{"__proto__":{"position":[0,0,0],"rotation":[0,0,0]}}')}]}), SceneDocumentError);
assert.throws(() => state.add('missing'), SceneDocumentError);
const detached = state.document;
detached.instances[0].position[0] = 987;
assert.notEqual(state.document.instances[0].position[0], 987);
const changes = [];
state.subscribe((document) => changes.push(document.name));
state.rename('Workshop arrangement');
assert.deepEqual(changes, ['Workshop arrangement']);
state.replace(State.empty('New scene'));
assert.equal(state.document.instances.length, 0);
state.undo();
assert.equal(state.document.name, 'Workshop arrangement');
console.log('Scene Builder state: robot placement, subtree offsets, joints, duplicate, history and strict JSON validation passed');
// %% mesh units and resource provenance survive draft interchange
const provenance = [{name: 'NOTICE.md', url: '/workshop/api/scene-builder/resource/private_meshes/NOTICE.md'}];
const scaled = new State([{...assets[0], notices: provenance}]);
const scaledBench = scaled.add('bench');
assert.deepEqual(plain(scaled.document.notices), provenance);
scaled.setScale(scaledBench.id, [0.001, 0.001, 0.001]);
assert.deepEqual(plain(scaled.instance(scaledBench.id).scale), [0.001, 0.001, 0.001]);
assert.throws(() => scaled.setScale(scaledBench.id, [1, 0, 1]), SceneDocumentError);
assert.throws(() => scaled.transform(scaledBench.id, {position: [10001, 0, 0], rotation: [0, 0, 0]}), SceneDocumentError);
assert.throws(() => State.validate({...plain(scaled.document), notices: [{name: 'unsafe', url: 'javascript:alert(1)'}]}), SceneDocumentError);
assert.throws(() => State.validate({...plain(scaled.document), instances: [{...plain(scaledBench), linkOffsets: []}]}), SceneDocumentError);

// %% atomic scale gestures and persistent locked scan references
const scanAsset = {id: 'point-clouds/scan.ply', name: 'Room scan', category: 'point-cloud', kind: 'point-cloud', format: 'ply'};
const scanState = new State([...assets, scanAsset]);
const scan = scanState.add(scanAsset.id, {name: 'Measured room', scale: [.001, .001, .001]});
assert.deepEqual(plain(scan.pointCloud), plain(State.POINT_CLOUD_DEFAULTS));
assert.equal(scan.name, 'Measured room');
assert.deepEqual(plain(scan.scale), [.001, .001, .001]);
const lockedDocument = scanState.export();
assert.throws(() => scanState.transform(scan.id, {position: [1, 0, 0], rotation: [0, 0, 0]}), SceneDocumentError);
assert.throws(() => scanState.setScale(scan.id, [1, 1, 1]), SceneDocumentError);
assert.equal(scanState.export(), lockedDocument);
scanState.setPointCloud(scan.id, {locked: false, opacity: .4, pointSize: .01, visible: true});
const beforeGesture = scanState.export();
scanState.transform(scan.id, {position: [1, 2, 3], rotation: [0, 0, .3], scale: [2, 3, 4]});
assert.deepEqual(plain(scanState.instance(scan.id).scale), [2, 3, 4]);
scanState.undo();
assert.equal(scanState.export(), beforeGesture, 'Pose and scale must undo as one gesture.');
scanState.redo();
const importedScan = new State([...assets, scanAsset], JSON.parse(scanState.export()));
assert.deepEqual(plain(importedScan.instance(scan.id).pointCloud), {visible: true, locked: false, pointSize: .01, opacity: .4});
const beforeInvalid = scanState.export();
for (const change of [{opacity: NaN}, {opacity: 0}, {pointSize: .2}, {pointSize: 0}, {visible: 1}, {locked: 'false'}, {unknown: true}]) assert.throws(() => scanState.setPointCloud(scan.id, change), SceneDocumentError);
assert.equal(scanState.export(), beforeInvalid);
const scalableBench = scanState.add('bench');
assert.equal(Object.hasOwn(scalableBench, 'pointCloud'), false, 'Existing mesh and URDF instances retain their schema.');
assert.throws(() => scanState.transform(scalableBench.id, {position: [0, 0, 0], rotation: [0, 0, 0], scale: [2, 2, 2]}, 'drawer'), SceneDocumentError);
assert.throws(() => scanState.transform(scalableBench.id, {position: [8, 0, 0], rotation: [0, 0, 0], scale: [-1, 1, 1]}), SceneDocumentError);
assert.deepEqual(plain(scanState.instance(scalableBench.id).position), [0, 0, 0]);
